import { requestUrl } from 'obsidian';
import type { OAuthManager } from '@/auth/oauth-manager';
import { GOOGLE_SCANS_FOLDER } from '@/config';
import { logger } from '@/utils/logger';

const DRIVE_API_BASE = 'https://www.googleapis.com/drive/v3';
const DRIVE_UPLOAD_BASE = 'https://www.googleapis.com/upload/drive/v3';

const SAMPLE_MARKDOWN = `# Quick meeting notes

- Discussed Q2 roadmap
- Action items for next week
- Follow up with design team on wireframes

**Key takeaway:** Ship the MVP first, iterate later.`;

export async function createFakeScanOnDrive(oauthManager: OAuthManager): Promise<void> {
	const token = await oauthManager.getValidAccessToken();

	const now = new Date();
	const dateShort = now.toISOString().split('T')[0]!;
	const hours = String(now.getUTCHours()).padStart(2, '0');
	const minutes = String(now.getUTCMinutes()).padStart(2, '0');
	const seconds = String(now.getUTCSeconds()).padStart(2, '0');
	const scanId = `${dateShort}-${hours}${minutes}${seconds}-dev`;

	const scanFile = {
		version: 1,
		createdAt: now.toISOString(),
		markdown: SAMPLE_MARKDOWN,
		confidence: 92,
		provider: 'dev-mock',
		model: 'fake-scan',
		imageFileName: `${scanId}.jpg`,
	};

	logger.info(`Dev: creating fake scan ${scanId}`);

	// Find or create the scans folder
	const folderId = await findOrCreateFolder(token, GOOGLE_SCANS_FOLDER);
	logger.info(`Dev: scans folder ID: ${folderId}`);

	// Step 1: Create JSON file (metadata + content in one call)
	const jsonFileId = await createDriveFile(
		token,
		`${scanId}.json`,
		folderId,
		'application/json',
		JSON.stringify(scanFile)
	);
	logger.info(`Dev: uploaded JSON file ${jsonFileId}`);

	// Step 2: Create placeholder image
	const imageFileId = await createDriveFile(
		token,
		`${scanId}.jpg`,
		folderId,
		'image/jpeg',
		createPlaceholderJpeg()
	);
	logger.info(`Dev: uploaded image file ${imageFileId}`);

	logger.info(`Dev: uploaded fake scan ${scanId} to Drive`);
}

async function findOrCreateFolder(token: string, folderPath: string): Promise<string> {
	const parts = folderPath.split('/');
	let parentId = 'root';

	for (const part of parts) {
		const query = `name = '${part}' and '${parentId}' in parents and mimeType = 'application/vnd.google-apps.folder' and trashed = false`;
		const response = await requestUrl({
			url: `${DRIVE_API_BASE}/files?q=${encodeURIComponent(query)}&fields=files(id)`,
			headers: { Authorization: `Bearer ${token}` },
		});

		interface DriveListResult { files?: Array<{ id: string }> }
		const data = response.json as DriveListResult;
		const folders = data.files ?? [];

		if (folders.length > 0 && folders[0]) {
			parentId = folders[0].id;
		} else {
			const createResponse = await requestUrl({
				url: `${DRIVE_API_BASE}/files`,
				method: 'POST',
				headers: {
					Authorization: `Bearer ${token}`,
					'Content-Type': 'application/json',
				},
				body: JSON.stringify({
					name: part,
					mimeType: 'application/vnd.google-apps.folder',
					parents: [parentId],
				}),
			});
			interface CreateResult { id: string }
			parentId = (createResponse.json as CreateResult).id;
		}
	}

	return parentId;
}

async function createDriveFile(
	token: string,
	name: string,
	parentId: string,
	mimeType: string,
	content: string | Uint8Array
): Promise<string> {
	logger.info(`Dev: creating Drive file "${name}" (${mimeType})`);

	// Step 1: Create file metadata
	const metaResponse = await requestUrl({
		url: `${DRIVE_API_BASE}/files`,
		method: 'POST',
		headers: {
			Authorization: `Bearer ${token}`,
			'Content-Type': 'application/json',
		},
		body: JSON.stringify({ name, parents: [parentId] }),
	});

	interface CreateResult { id: string }
	const fileId = (metaResponse.json as CreateResult).id;
	logger.info(`Dev: created file metadata, ID: ${fileId}`);

	// Step 2: Upload content
	await requestUrl({
		url: `${DRIVE_UPLOAD_BASE}/files/${fileId}?uploadType=media`,
		method: 'PATCH',
		headers: {
			Authorization: `Bearer ${token}`,
			'Content-Type': mimeType,
		},
		// TS 5.9 / @types/node 24 type `Uint8Array.buffer` as ArrayBufferLike
		// (ArrayBuffer | SharedArrayBuffer). Dev placeholder content is always a
		// plain ArrayBuffer-backed array, so narrow it for requestUrl's body type.
		body: typeof content === 'string' ? content : (content.buffer as ArrayBuffer),
	});

	logger.info(`Dev: uploaded content for "${name}"`);
	return fileId;
}

